import { createContext, useContext, useState } from "react";

export type Lang = "ar" | "en";

interface LangCtx { lang: Lang; setLang: (l: Lang) => void; }
export const LangContext = createContext<LangCtx>({ lang: "ar", setLang: () => {} });
export const useLang = () => useContext(LangContext);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("lumina_lang") as Lang;
    return saved === "ar" || saved === "en" ? saved : "ar";
  });
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem("lumina_lang", l); };
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export const formatNumber = (value: number, maximumFractionDigits = 0) =>
  new Intl.NumberFormat("en-US", { maximumFractionDigits }).format(value);

