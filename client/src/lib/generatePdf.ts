// ─── Prices ───────────────────────────────────────────────────────────────────
const DEFAULT_PRICES = {
  panelPerWatt: 55, batteryPerAh12V: 145, inverterPerWatt: 28,
  regulatorPerAmp: 450, installationPct: 15, cableAndMiscFixed: 25000,
  sonelgazTariff: 5.0,
};

export function computeDefaultCosts(type: string, results: any) {
  const panelsCost    = (results.systemCapacitykW || 0) * 1000 * DEFAULT_PRICES.panelPerWatt;
  const batteriesCost = (type === "off-grid" || type === "hybrid")
    ? (results.totalBatteries || 0) * 200 * DEFAULT_PRICES.batteryPerAh12V : 0;
  const inverterW     = type === "on-grid"
    ? (results.inverterCapacitykW || 0) * 1000 : (results.inverterCapacityW || 0);
  const inverterCost  = inverterW * DEFAULT_PRICES.inverterPerWatt;
  const regulatorCost = (results.mpptRatingA || 0) * DEFAULT_PRICES.regulatorPerAmp;
  const materialCost  = panelsCost + batteriesCost + inverterCost + regulatorCost + DEFAULT_PRICES.cableAndMiscFixed;
  const installCost   = materialCost * (DEFAULT_PRICES.installationPct / 100);
  const total         = materialCost + installCost;
  const annualKwh     = type === "on-grid" && results.dailyProductionkWh
    ? results.dailyProductionkWh * 365
    : (results.systemCapacitykW || 0) * 5 * 365 * 0.82;
  const annualSavings = annualKwh * DEFAULT_PRICES.sonelgazTariff;
  const paybackYears  = total / (annualSavings || 1);
  const savingsOver25 = annualSavings * 25 - total;
  return {
    costs: { panels: panelsCost, batteries: batteriesCost, inverter: inverterCost, regulator: regulatorCost, cableAndMisc: DEFAULT_PRICES.cableAndMiscFixed, installation: installCost, total },
    roi:   { annualSavings, paybackYears, savingsOver25 },
  };
}

